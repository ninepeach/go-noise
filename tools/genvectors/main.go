// Command genvectors writes go-noise's extended reference vectors, using
// github.com/flynn/noise as an independent implementation.
//
// It lives in its own module so that go-noise itself gains no dependency.
// Regenerate with:  make vectors
package main

import (
	"bytes"
	"encoding/hex"
	"fmt"
	"io"
	"log"
	"os"

	"github.com/flynn/noise"
)

type suite struct{ cipher, hash string }

var (
	allSuites = []suite{{"AESGCM", "SHA256"}, {"ChaChaPoly", "BLAKE2s"}, {"AESGCM", "SHA512"}, {"ChaChaPoly", "BLAKE2b"}}
	// The first vector file already holds these four patterns with SHA256/BLAKE2s, so only the
	// 64-byte hashes are added for them.
	longHashSuites = []suite{{"AESGCM", "SHA512"}, {"ChaChaPoly", "BLAKE2b"}}
	alreadyCovered = map[string]bool{"NN": true, "NK": true, "IK": true, "XX": true}
)

var patterns = []struct {
	name    string
	pattern noise.HandshakePattern
}{
	{"NN", noise.HandshakeNN}, {"KN", noise.HandshakeKN}, {"NK", noise.HandshakeNK}, {"KK", noise.HandshakeKK},
	{"NX", noise.HandshakeNX}, {"KX", noise.HandshakeKX}, {"XN", noise.HandshakeXN}, {"IN", noise.HandshakeIN},
	{"XK", noise.HandshakeXK}, {"IK", noise.HandshakeIK}, {"XX", noise.HandshakeXX}, {"XXfallback", noise.HandshakeXXfallback},
	{"IX", noise.HandshakeIX}, {"N", noise.HandshakeN}, {"K", noise.HandshakeK}, {"X", noise.HandshakeX},
}

func seed(start int) []byte {
	b := make([]byte, 32)
	for i := range b {
		b[i] = byte(start + 3*i)
	}
	return b
}

func has(list []noise.MessagePattern, tok noise.MessagePattern) bool {
	for _, t := range list {
		if t == tok {
			return true
		}
	}
	return false
}

// writesStatic reports whether the party sends or pre-shares a static key.
func needsStatic(p noise.HandshakePattern, initiator bool) bool {
	pre := p.ResponderPreMessages
	if initiator {
		pre = p.InitiatorPreMessages
	}
	if has(pre, noise.MessagePatternS) {
		return true
	}
	for i, m := range p.Messages {
		if (i%2 == 0) == initiator && has(m, noise.MessagePatternS) {
			return true
		}
	}
	return false
}

func keypair(s []byte) noise.DHKey {
	k, err := noise.DH25519.GenerateKeypair(bytes.NewReader(s))
	if err != nil {
		log.Fatal(err)
	}
	return k
}

func main() {
	out := io.Writer(os.Stdout)
	fmt.Fprintln(out, "# go-noise extended reference vectors, version 1")
	fmt.Fprintln(out, "# Generated by tools/genvectors with github.com/flynn/noise as an independent reference implementation.")
	fmt.Fprintln(out, "# Deterministic test keys only; never use these keys in production.")
	fmt.Fprintln(out, "# XXfallback with a preshared key is deliberately absent: flynn/noise spells that protocol name")
	fmt.Fprintln(out, "# without the plus sign the Noise specification requires (XXfallback+psk0), so it is no valid reference.")
	fmt.Fprintln(out)
	count := 0
	for _, entry := range patterns {
		suites := allSuites
		if alreadyCovered[entry.name] {
			suites = longHashSuites
		}
		last := len(entry.pattern.Messages)
		for placement := -1; placement <= last; placement++ {
			if placement >= 0 && entry.name == "XXfallback" {
				continue
			}
			for _, s := range suites {
				emit(out, entry.name, entry.pattern, placement, s)
				count++
			}
		}
	}
	fmt.Fprintf(os.Stderr, "wrote %d vectors\n", count)
}

func emit(out io.Writer, name string, p noise.HandshakePattern, placement int, s suite) {
	ciphers := map[string]noise.CipherFunc{"AESGCM": noise.CipherAESGCM, "ChaChaPoly": noise.CipherChaChaPoly}
	hashes := map[string]noise.HashFunc{"SHA256": noise.HashSHA256, "SHA512": noise.HashSHA512, "BLAKE2b": noise.HashBLAKE2b, "BLAKE2s": noise.HashBLAKE2s}
	suiteImpl := noise.NewCipherSuite(noise.DH25519, ciphers[s.cipher], hashes[s.hash])

	initSeed, respSeed, initEph, respEph := seed(0x11), seed(0x71), seed(0x31), seed(0x91)
	prologue := []byte("go-noise independent vector suite v1")
	psk := []byte("go-noise-test-psk-32-bytes-fixed")
	initStatic, respStatic := keypair(initSeed), keypair(respSeed)
	initEphKP, respEphKP := keypair(initEph), keypair(respEph)

	initNeeds, respNeeds := needsStatic(p, true), needsStatic(p, false)
	ic := noise.Config{CipherSuite: suiteImpl, Pattern: p, Initiator: true, Random: bytes.NewReader(initEph), Prologue: prologue, PresharedKeyPlacement: -1}
	rc := noise.Config{CipherSuite: suiteImpl, Pattern: p, Initiator: false, Random: bytes.NewReader(respEph), Prologue: prologue, PresharedKeyPlacement: -1}
	if initNeeds {
		ic.StaticKeypair = initStatic
	}
	if respNeeds {
		rc.StaticKeypair = respStatic
	}
	if has(p.ResponderPreMessages, noise.MessagePatternS) {
		ic.PeerStatic = respStatic.Public
	}
	if has(p.InitiatorPreMessages, noise.MessagePatternS) {
		rc.PeerStatic = initStatic.Public
	}
	if has(p.ResponderPreMessages, noise.MessagePatternE) {
		rc.EphemeralKeypair, ic.PeerEphemeral = respEphKP, respEphKP.Public
	}
	if has(p.InitiatorPreMessages, noise.MessagePatternE) {
		ic.EphemeralKeypair, rc.PeerEphemeral = initEphKP, initEphKP.Public
	}
	protocol := "Noise_" + name
	if placement >= 0 {
		ic.PresharedKey, rc.PresharedKey = psk, psk
		ic.PresharedKeyPlacement, rc.PresharedKeyPlacement = placement, placement
		protocol += fmt.Sprintf("psk%d", placement)
	}
	protocol += "_25519_" + s.cipher + "_" + s.hash

	ini, err := noise.NewHandshakeState(ic)
	if err != nil {
		log.Fatalf("%s: %v", protocol, err)
	}
	resp, err := noise.NewHandshakeState(rc)
	if err != nil {
		log.Fatalf("%s: %v", protocol, err)
	}

	fmt.Fprintf(out, "handshake=%s\n", protocol)
	if initNeeds {
		fmt.Fprintf(out, "init_static=%x\n", initSeed)
	}
	if respNeeds {
		fmt.Fprintf(out, "resp_static=%x\n", respSeed)
	}
	fmt.Fprintf(out, "gen_init_ephemeral=%x\n", initEph)
	fmt.Fprintf(out, "gen_resp_ephemeral=%x\n", respEph)
	fmt.Fprintf(out, "prologue=%x\n", prologue)
	if placement >= 0 {
		fmt.Fprintf(out, "preshared_key=%x\n", psk)
	}

	var iSend, iRecv, rSend, rRecv *noise.CipherState
	msg := 0
	line := func(payload, ciphertext []byte) {
		fmt.Fprintf(out, "msg_%d_payload=%s\n", msg, hex.EncodeToString(payload))
		fmt.Fprintf(out, "msg_%d_ciphertext=%s\n", msg, hex.EncodeToString(ciphertext))
		msg++
	}
	for i := range p.Messages {
		writer, reader := ini, resp
		if i%2 == 1 {
			writer, reader = resp, ini
		}
		payload := []byte(fmt.Sprintf("go-noise handshake %s message %d", name, i))
		ct, a, b, err := writer.WriteMessage(nil, payload)
		if err != nil {
			log.Fatalf("%s message %d: %v", protocol, i, err)
		}
		got, c, d, err := reader.ReadMessage(nil, ct)
		if err != nil || !bytes.Equal(got, payload) {
			log.Fatalf("%s message %d read: %v", protocol, i, err)
		}
		line(payload, ct)
		if i == len(p.Messages)-1 {
			// flynn/noise returns (cs1, cs2) to both roles: cs1 carries initiator->responder traffic.
			wIsInit := i%2 == 0
			if wIsInit {
				iSend, iRecv = a, b
				rRecv, rSend = c, d
			} else {
				rRecv, rSend = a, b
				iSend, iRecv = c, d
			}
		}
	}
	transport := func(dir int, enc, dec *noise.CipherState) {
		payload := []byte(fmt.Sprintf("go-noise transport direction %d", dir))
		ct, err := enc.Encrypt(nil, nil, payload)
		if err != nil {
			log.Fatal(err)
		}
		if pt, err := dec.Decrypt(nil, nil, ct); err != nil || !bytes.Equal(pt, payload) {
			log.Fatalf("%s transport %d: %v", protocol, dir, err)
		}
		line(payload, ct)
	}
	transport(0, iSend, rRecv)
	if len(p.Messages) > 1 { // one-way patterns have no responder-to-initiator direction
		transport(1, rSend, iRecv)
	}
	fmt.Fprintln(out)
}
